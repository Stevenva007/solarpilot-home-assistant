"""Actual Chromium probes for read-only Panasonic cooling explanations.

The source observations are generated by the shipped monitor using the existing
fictional runtime fixtures. Only local options-menu metadata may be requested;
no options save, external network request or actuator call is permitted.
"""
from copy import deepcopy
import os
from pathlib import Path
import shutil
import sys
import time
from types import SimpleNamespace

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(os.environ.get("SOLARPILOT_SCREENSHOT_DIR", "/tmp/solarpilot-browser-tests"))
ZONES = ("climate.fictional_downstairs", "climate.fictional_upstairs")


def runtime_fixtures():
    """Use production diagnostics; HA doubles supply fictional read observations."""
    sys.path.insert(0, str(ROOT))
    sys.path.insert(0, str(ROOT / "tests"))
    import conftest  # noqa: F401 — initialize isolated HA interface doubles.
    from test_cooling_diagnostics80 import monitor_fixture
    from test_sg_ui_platforms62 import attributes

    results = {}
    modes = {"heat": "heat", "auto_heat": "auto", "cool": "cool",
             "auto_unknown": "auto", "unavailable": "heat", "source_expired": "heat"}
    for case, mode in modes.items():
        runtime, hass = monitor_fixture(mode=mode, zones=list(ZONES))
        for index, entity_id in enumerate(ZONES):
            source_mode = "unavailable" if case == "unavailable" and index == 1 else mode
            hass.states.set(entity_id, source_mode,
                {"hvac_action": "cooling" if mode == "cool" else "idle",
                 "friendly_name": f"Fictional room {index + 1}"},
                reported_age=121 if case == "source_expired" and index == 1 else 0)
        if case == "auto_heat":
            def read_native(entity_id):
                stamp = hass.states.get(entity_id).last_reported.timestamp()
                return {"entity_id": entity_id, "program": "heating", "raw_mode": "AUTO_HEAT",
                        "source": "aquarea_poll", "fresh": True, "observed_at": stamp, "stale_s": 120}
            runtime.panasonic.native_program = SimpleNamespace(read=read_native)
        overview = runtime.panasonic.overview()
        data = attributes(profile="general", profile_confirmed=True,
                          cooling_protection_confirmed=False)
        data.update(solar_pilot=True, config_entry_id="fixture-cooling80")
        data["panasonic"].update(overview)
        data["sg_boost"]["cooling_diagnostic"] = deepcopy(overview["cooling_context_diagnostic"])
        results[case] = data
        assert not hass.services.calls, case
    return {"cases": results, "clock_ms": int(time.time() * 1000)}


SETUP_JS = r"""fixture => {
  window.c=document.querySelector('solar-pilot-card');
  window.qaOriginalClock=Date.now;window.qaClockMs=fixture.clock_ms;window.qaBaseClockMs=fixture.clock_ms;
  Date.now=()=>qaClockMs;window.qaCases=fixture.cases;
  window.qaPreviewBase=structuredClone(c._last.attributes);
  window.qaServiceCalls=[];window.qaOptionsCalls=[];window.qaAttackCount=0;
  window.qaAttack=()=>qaAttackCount++;
  const flowId='fixture-cooling80-flow';
  const menu=(step,options)=>({type:'menu',step_id:step,flow_id:flowId,menu_options:options});
  const api=async(method,path,data)=>{
    qaOptionsCalls.push({method,path,data:data??null});
    if(method==='delete'&&path==='config/config_entries/options/flow/'+flowId)return {};
    if(method!=='post')throw Error('Unexpected non-metadata request');
    if(path==='config/config_entries/options/flow'&&JSON.stringify(data)==='{"handler":"fixture-cooling80"}')
      return menu('init',['comfort_hub','loads_hub']);
    if(path==='config/config_entries/options/flow/'+flowId&&JSON.stringify(data)==='{"next_step_id":"comfort_hub"}')
      return menu('comfort_hub',['panasonic_monitor','sg_boost','comfort']);
    if(path==='config/config_entries/options/flow/'+flowId&&JSON.stringify(data)==='{"next_step_id":"sg_boost"}')
      return {type:'form',step_id:'sg_boost',flow_id:flowId,errors:{},data_schema:[
        {name:'zone_entities',required:false,description:{suggested_value:['climate.fictional_downstairs','climate.fictional_upstairs']},
          selector:{entity:{domain:'climate',multiple:true}}},
        {name:'cooling_protection_confirmed',required:false,description:{suggested_value:false},selector:{boolean:{}}}]};
    throw Error('Options save or unrelated route forbidden by browser probe');
  };
  window.qaHass={...c._hass,user:{id:'fixture-cooling-admin',is_admin:true},callApi:api,
    callService:async(...args)=>{qaServiceCalls.push(args);throw Error('Actuator call forbidden');},
    states:{...c._hass.states,
      'climate.fictional_downstairs':{state:'auto',attributes:{friendly_name:'Fictional room 1'}},
      'climate.fictional_upstairs':{state:'auto',attributes:{friendly_name:'Fictional room 2'}}}};
  window.qaApply=(caseName,unsafe=false)=>{
    qaClockMs=qaBaseClockMs;
    const data=structuredClone(qaCases[caseName]);
    if(unsafe){
      const d=data.sg_boost.cooling_diagnostic;
      d.sources[0].name='<img src=x onerror="qaAttack()">';
      d.sources[0].entity_id='climate.<script>qaAttack()</script>';
      d.sources[0].native_reason='<svg onload="qaAttack()">';
      d.summary='<script>qaAttack()</script>';d.action='<img src=x onerror="qaAttack()">';
    }
    const a={...structuredClone(qaPreviewBase),...data};
    c.hass={...qaHass,states:{...qaHass.states,[c._entity]:{state:'Fictional current observations',attributes:a}}};
  };
  const style=document.createElement('style');
  style.textContent='body{margin:0;padding:8px;max-width:1100px;box-sizing:border-box}';
  document.head.append(style);qaApply('heat');
}"""

EXPIRE_JS = r"""() => {
  window.qaSavedState=c._last;window.qaSavedAttributes=JSON.stringify(c._last.attributes);
  window.qaSavedDialog=c._optionsDialog;
  qaClockMs=qaBaseClockMs+121000;c._refreshObservationDisplay();
}"""

UNCHANGED_JS = r"""() => c._last===qaSavedState&&JSON.stringify(c._last.attributes)===qaSavedAttributes
  &&c._optionsDialog===qaSavedDialog&&c._last.attributes.sg_boost.cooling_protection_confirmed===false"""


def opened_details(card, view):
    key = "overview:sg:why" if view == "overview" else f"sg:{view}:details"
    details = card.locator(f'[data-ui-key="{key}"]')
    assert details.count() == 1, (view, key)
    if details.get_attribute("open") is None:
        details.locator(":scope > summary").click()
    return details


def assert_layout(page, diagnostic):
    assert page.evaluate("document.documentElement.scrollWidth<=innerWidth+1")
    assert diagnostic.evaluate("el=>el.scrollWidth<=el.clientWidth+1")
    for row in diagnostic.locator(".sg-cooling-source").all():
        assert row.evaluate("el=>el.scrollWidth<=el.clientWidth+1")


def main():
    fixture = runtime_fixtures()
    expected = {"heat": "heating_only_confirmed", "auto_heat": "heating_only_confirmed",
                "cool": "cooling_present", "auto_unknown": "auto_program_unknown",
                "unavailable": "zone_source_unavailable", "source_expired": "zone_source_stale"}
    for case, code in expected.items():
        value = fixture["cases"][case]["sg_boost"]["cooling_diagnostic"]
        assert value["schema"] == 1 and value["read_only"] is True and value["code"] == code
        assert len(value["sources"]) == 2
    OUT.mkdir(parents=True, exist_ok=True)
    errors, samples, routes, expiry_checks = [], 0, 0, 0
    with sync_playwright() as playwright:
        executable = os.environ.get("SOLARPILOT_CHROMIUM_PATH") or shutil.which("chromium")
        browser = playwright.chromium.launch(**({"executable_path": executable} if executable else {}),
                                             headless=True, args=["--no-sandbox"])
        for width in (320, 390, 768, 1440):
            page = browser.new_page(viewport={"width": width, "height": 1000},
                                    locale="nl-BE", timezone_id="Europe/Brussels")
            page.route("**/*", lambda route: route.abort())
            page.on("pageerror", lambda error: errors.append(str(error)))
            page.set_content((ROOT / "SolarPilot-voorbeeld.html").read_text(encoding="utf-8"), wait_until="load")
            page.wait_for_selector("solar-pilot-card >> h1")
            page.evaluate(SETUP_JS, fixture)
            card = page.locator("solar-pilot-card")
            for view in ("overview", "comfort", "loads"):
                card.locator(f'.nav > button[role=tab][data-action=view][data-value={view}]').click()
                details = opened_details(card, view)
                diagnostic = details.locator(".sg-cooling-diagnostic")
                for case, code in expected.items():
                    page.evaluate("caseName=>qaApply(caseName)", case)
                    assert details.get_attribute("open") is not None, (width, view, case)
                    assert diagnostic.get_attribute("data-sg-cooling-code") == code, (width, view, case)
                    assert diagnostic.locator(".sg-cooling-source").count() == 2
                    text = diagnostic.inner_text()
                    for entity_id in ZONES:
                        assert entity_id in text
                    assert "Fictional room 1" in text and "Fictional room 2" in text
                    for label in ("Laatste bronmelding", "Werkelijk Panasonic-programma", "Programmabron"):
                        assert label in text
                    assert "Tankopwarming en sterilisatie wijzigen deze koelvoorwaarde niet" in text
                    assert fixture["cases"][case]["sg_boost"]["cooling_diagnostic"]["summary"] in text
                    assert fixture["cases"][case]["sg_boost"]["cooling_diagnostic"]["action"] in text
                    if code == "heating_only_confirmed":
                        assert "Koeling uitgesloten door actuele gekoppelde bronnen" in text
                        if case == "auto_heat":
                            assert "AUTO_HEAT" in text and "aquarea_poll" in text
                    else:
                        assert "Koelvoorwaarde wacht op betrouwbare context of bevestigde fysieke beveiliging" in text
                        assert "Koeling uitgesloten door actuele gekoppelde bronnen" not in text
                    if case == "source_expired":
                        assert "Bronmelding verouderd of ongeldig" in text
                    if case == "unavailable":
                        assert "Entiteit niet beschikbaar" in text
                    assert_layout(page, diagnostic)
                    samples += 1

                # All escaped source labels and provider explanations stay text,
                # including on narrow views. No injected node or handler is run.
                page.evaluate("()=>qaApply('auto_unknown',true)")
                assert diagnostic.locator("script,img,svg").count() == 0
                assert "<img" in diagnostic.inner_text() and "<script>" in diagnostic.inner_text()
                assert page.evaluate("qaAttackCount") == 0
                assert_layout(page, diagnostic)
                if width == 390:
                    page.evaluate("()=>qaApply('auto_unknown')")
                    page.screenshot(path=str(OUT / f"SolarPilot-cooling80-{view}.png"), full_page=True)

                # The real diagnostic button must navigate through the native
                # comfort menu to precisely sg_boost, without submitting a form.
                page.evaluate("()=>{qaApply('heat');qaOptionsCalls=[];}")
                monitor = details.locator(f'[data-ui-key="sg:{view}:monitor"]')
                if monitor.get_attribute("open") is None:
                    monitor.locator(":scope > summary").click()
                diagnostic.locator('button[data-action=configure][data-config-step=sg_boost]').click()
                options = page.locator("solar-pilot-options-dialog")
                options.locator('[name="cooling_protection_confirmed"]').wait_for(state="visible")
                assert page.evaluate("c._optionsDialog.flow.step_id") == "sg_boost"
                assert page.evaluate("qaOptionsCalls.map(row=>row.data)") == [
                    {"handler": "fixture-cooling80"}, {"next_step_id": "comfort_hub"}, {"next_step_id": "sg_boost"}]
                assert options.locator('[name="zone_entities"] option:checked').count() == 2
                assert not options.locator('[name="cooling_protection_confirmed"]').is_checked()
                options.locator('[name="cooling_protection_confirmed"]').check()
                routes += 1

                # Advancing the real display clock alone expires previously
                # valid heating evidence. The modal draft and both explanations
                # remain open; the HA state and local protection value stay exact.
                page.evaluate(EXPIRE_JS)
                assert diagnostic.get_attribute("data-sg-cooling-code") == "context_expired"
                assert "De Panasonic-koelcontext is verouderd" in diagnostic.text_content()
                assert "Koeling uitgesloten door actuele gekoppelde bronnen" not in diagnostic.text_content()
                assert details.get_attribute("open") is not None
                assert monitor.get_attribute("open") is not None
                assert options.locator("dialog").first.is_visible()
                assert options.locator('[name="cooling_protection_confirmed"]').is_checked()
                assert page.evaluate(UNCHANGED_JS)
                assert page.evaluate("qaOptionsCalls.length") == 3
                assert page.evaluate("qaServiceCalls.length") == 0
                expiry_checks += 1
                page.evaluate("async()=>{qaClockMs=qaBaseClockMs;await c._optionsDialog.close(true);}")
                assert page.evaluate("qaOptionsCalls.length") == 4
                assert page.evaluate("qaOptionsCalls.at(-1).method") == "delete"
                assert page.evaluate("qaServiceCalls.length") == 0
            page.close()
        assert not errors, errors
        browser.close()
    print(f"Cooling UI: {samples} actual runtime cases, 3 views × 4 widths, {routes} exact SG metadata routes, "
          f"{expiry_checks} no-state display expiry checks, preserved explanations/drafts and escaped source text: OK; "
          "0 options saves / actuator calls; external network blocked")


if __name__ == "__main__":
    main()
