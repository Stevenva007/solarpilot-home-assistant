TRIPLES = ((CONTRACT_ID, "special_status", SEMANTIC_CONTRACT_ID),
           (OPERATION_CONTRACT_ID, "operation_status", OPERATION_SEMANTIC_CONTRACT_ID))


def render_unchanged(data, *, view="board"):
    before = deepcopy(data)
    learner = classify_heatpump_observation(data["panasonic"], now_wall=data["_test_clock"])
    result, root = parsed(data, view)
    assert result["calls"] == []
    assert data == before
    assert classify_heatpump_observation(data["panasonic"], now_wall=data["_test_clock"]) == learner
    return root


@pytest.mark.parametrize("identity,semantics,marker", tuple(product(range(2), repeat=3)))
def test_only_the_two_complete_capture_time_contract_triples_reach_the_card(identity, semantics, marker):
    data = status_snapshot()
    contract = data["panasonic"]["source_contract"]
    contract.update(contract_id=TRIPLES[identity][0], action_semantics=TRIPLES[semantics][1])
    contract["compatibility"]["contract"] = TRIPLES[marker][2]
    # Test the card's independent boundary against a previously valid result.
    data["panasonic"]["operation_display"]["source_contract_id"] = contract["contract_id"]
    task = business_tile(render_unchanged(data), "data-heatpump-task")
    if identity == semantics == marker:
        assert task.attributes["data-heatpump-task"] == "inferred"
        assert "Verwarmen" in task.text() and "onbekend" not in task.text()
    else:
        assert task.attributes["data-heatpump-task"] == "activity"
        assert "taak onbekend" in task.text()


@pytest.mark.parametrize("mapping", ["special", "operation"])
@pytest.mark.parametrize("limit", [30, 120])
def test_original_oldest_meter_deadline_expires_task_without_refreshing_other_evidence(mapping, limit):
    data = status_snapshot(mapping=mapping)
    p = data["panasonic"]
    p["power_activity"]["stale_s"] = limit
    p.update(compressor_entity="sensor.synthetic_frequency", compressor_frequency_hz=42,
             compressor_frequency_observed_at=NOW-1)
    p["operation_display"] = classify_display_operation(p, now_wall=NOW)
    display = deepcopy(p["operation_display"])
    assert display["tier"] == "derived" and display["model_eligible"] is False
    assert display["observed_at"] == NOW-5
    assert display["valid_until"] == NOW-5+limit
    data["_test_clock"] = display["valid_until"]-.01
    assert "Verwarmen" in business_tile(render_unchanged(data), "data-heatpump-task").text()
    # The independent newer activity can survive the thermal task deadline.
    # No source or backend presentation is regenerated by this later render.
    data["_test_clock"] = display["valid_until"]
    task = business_tile(render_unchanged(data), "data-heatpump-task")
    assert task.attributes["data-heatpump-task"] == "activity"
    assert "Actief · taak onbekend" in task.text()
    assert p["operation_display"] == display


@pytest.mark.parametrize("problem", ["missing", "negative", "boolean", "string", "invalid", "old",
                                     "future", "unassigned", "duplicate_number", "different_individual"])
def test_invalid_or_unassigned_main_meter_never_labels_space_heating(problem):
    data = status_snapshot()
    p = data["panasonic"]
    rows = p["power_activity"]["supplies"]
    row = rows[0]
    if problem == "missing": row["watts"] = None
    elif problem == "negative": row["watts"] = -1
    elif problem == "boolean": row["watts"] = True
    elif problem == "string": row["watts"] = "1300"
    elif problem == "invalid": row["valid"] = False
    elif problem == "old": row["observed_at"] = NOW-121
    elif problem == "future": row["observed_at"] = NOW+6
    elif problem == "unassigned": row["role"] = "unconfirmed"
    elif problem == "duplicate_number": rows[1]["number"] = 1
    else: p["power_supply1_w"] = 2200
    p["operation_display"] = classify_display_operation(p, now_wall=NOW)
    assert p["operation_display"]["function"] is None
    assert p["operation_display"]["tier"] == "unknown"
    root = render_unchanged(data)
    tiles = [n for n in root.walk() if "data-heatpump-task" in n.attributes]
    assert all(n.attributes["data-heatpump-task"] == "activity" for n in tiles)
    assert all("Verwarmen" not in n.text() for n in tiles)
    assert classify_heatpump_observation(p, now_wall=NOW)["model_eligible"] is False


@pytest.mark.parametrize("problem", ["wrong_native_task", "route_idle", "route_wrong_task", "zone_direction",
                                     "zone_disabled", "tank_heating", "foreign_tank", "native_conflict"])
def test_conflicting_live_route_or_task_is_not_repaired_by_frontend_contract_acceptance(problem):
    data = status_snapshot()
    p, c = data["panasonic"], data["panasonic"]["source_contract"]
    if problem == "wrong_native_task": c["raw_device_action"] = "HEATING_WATER"
    elif problem == "route_idle": c["direction"]["state"] = "IDLE"
    elif problem == "route_wrong_task": c["direction"]["state"] = "WATER"
    elif problem == "zone_direction": c["zones"][0]["state"] = "cool"
    elif problem == "zone_disabled": c["zones"][0]["enabled"] = False
    elif problem == "tank_heating": p["display_tank"]["action"] = "heating"
    elif problem == "foreign_tank": p["display_tank"]["entity_id"] = "water_heater.synthetic_unrelated"
    else: p["native_task"]["conflict"] = True
    p["operation_display"] = classify_display_operation(p, now_wall=NOW)
    assert p["operation_display"]["function"] is None
    task = business_tile(render_unchanged(data), "data-heatpump-task")
    assert task.attributes["data-heatpump-task"] == "activity"
    assert "taak onbekend" in task.text()


