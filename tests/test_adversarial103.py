@pytest.mark.parametrize("function", ["space_heating", "space_cooling", "tapwater_heating"])
def test_display_acceptance_does_not_promote_learning_or_sg_feedback(function):
    data = status_snapshot(function=function)
    s = data["sg_boost"]
    s.update(desired_on=True, relay_on=True, relay_confirmed=True, panasonic_confirmed=None,
             policy_hold=True, policy_hold_reason="response_unknown")
    p = data["panasonic"]
    p.update(sg_status="unknown", sg_status_confirmed=False, sg_status_observed_at=None)
    before = deepcopy(data)
    evidence = classify_heatpump_observation(p, now_wall=NOW)
    assert evidence["tier"] == "derived" and evidence["model_eligible"] is False
    model = HeatPumpActivityModel()
    model.restore({"samples": {"space_heating": [900]}, "days": {"space_heating": ["2026-10-01"]}})
    retained = deepcopy(model.samples)
    for index in range(3):
        assert model.observe(NOW+index*5, "2026-10-21", evidence["context"], 1300,
                             evidence=evidence["tier"], detail=evidence) is False
    for view in ("board", "comfort"):
        task = business_tile(render_unchanged(data, view=view), "data-heatpump-task")
        assert task.attributes["data-heatpump-task"] == "inferred"
    assert model.samples == retained and model.confirmed_samples["space_heating"] == []
    assert data == before


def test_current_split_card_cannot_relabel_retained_special_status_evidence():
    old = status_snapshot(mapping="special")["panasonic"]["source_contract"]
    retained = contract_evidence(old, NOW, 120)
    before = deepcopy(retained)
    assert retained["contract_id"] == CONTRACT_ID
    assert retained["action_semantics"] == "special_status"
    assert "status_data_mode" not in retained
    data = status_snapshot()
    assert "Verwarmen" in business_tile(render_unchanged(data), "data-heatpump-task").text()
    assert retained_contract_evidence(retained, NOW, 120) == before
    assert retained == before
